CREATE TABLE IF NOT EXISTS inventory_items (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_qty NUMERIC NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS inventory_transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES inventory_items(item_id),
    transaction_type TEXT NOT NULL,
    quantity NUMERIC NOT NULL
);

CREATE OR REPLACE FUNCTION trg_update_stock_and_journal()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.quantity IS NULL THEN
        RAISE EXCEPTION 'Transaction quantity cannot be null';
    END IF;

    IF NEW.transaction_type = 'PURCHASE' THEN
        IF NEW.quantity <= 0 THEN
            RAISE EXCEPTION 'PURCHASE quantity must be greater than zero';
        END IF;

        UPDATE inventory_items
        SET stock_qty = stock_qty + NEW.quantity
        WHERE item_id = NEW.item_id;

    ELSIF NEW.transaction_type = 'SALE' THEN
        IF NEW.quantity <= 0 THEN
            RAISE EXCEPTION 'SALE quantity must be greater than zero';
        END IF;

        UPDATE inventory_items
        SET stock_qty = stock_qty - NEW.quantity
        WHERE item_id = NEW.item_id
          AND stock_qty >= NEW.quantity;

        IF NOT FOUND THEN
            RAISE EXCEPTION
                'Insufficient stock for item %: cannot sell quantity %',
                NEW.item_id,
                NEW.quantity;
        END IF;

    ELSIF NEW.transaction_type = 'ADJUSTMENT' THEN
        UPDATE inventory_items
        SET stock_qty = stock_qty + NEW.quantity
        WHERE item_id = NEW.item_id;

    ELSE
        RAISE EXCEPTION 'Unsupported transaction type: %', NEW.transaction_type;
    END IF;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Inventory item % does not exist', NEW.item_id;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_update_stock_and_journal
ON inventory_transactions;

CREATE TRIGGER trg_update_stock_and_journal
BEFORE INSERT ON inventory_transactions
FOR EACH ROW
EXECUTE FUNCTION trg_update_stock_and_journal();
